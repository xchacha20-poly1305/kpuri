#!/usr/bin/env python3
"""Generate portable commonTest cases from the pinned WPT corpus and reviewed expectations."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'kpuri/src/commonTest/wpt'
OUT = ROOT / 'kpuri/src/commonTest/kotlin/io/github/xchacha20_poly1305/kpuri/WptUrlTest.kt'

def literal(value):
    return json.dumps(value, ensure_ascii=True).replace('$', '\\$') if value is not None else 'null'

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated tests are stale")
    args = parser.parse_args()
    corpus = json.loads((DATA / 'urltestdata.json').read_text())
    cases = json.loads((DATA / 'expectations.json').read_text())
    lines = ['// Generated by scripts/generate_wpt_tests.py; edit wpt/expectations.json instead.',
             'package io.github.xchacha20_poly1305.kpuri', '',
             'import kotlin.test.Test', 'import kotlin.test.assertEquals',
             'import kotlin.test.assertFailsWith', '', 'class WptUrlTest {']
    for case in cases:
        index = case['index']
        upstream = corpus[index]
        assert upstream['input'] == case['input'], f'WPT index {index} changed'
        expected = case.get('expected', upstream.get('href'))
        assert 'reason' in case
        lines += ['', '    @Test', f'    fun case{index}() {{',
                  '        // ' + case['reason'], f'        val input = {literal(upstream["input"])}']
        if expected is None:
            lines += ['        assertFailsWith<UrlSyntaxException> { Url.parseReference(input) }']
        else:
            lines += [f'        val expected = {literal(expected)}',
                      '        val url = Url.parseReference(input)',
                      '        assertEquals(expected, url.toString())',
                      '        assertReparseStable(input)',
                      '        assertEquals(expected, url.newBuilder().build().toString())']
            if 'expected' not in case:
                # WHATWG getters collapse absent and empty components. Compare
                # populated fields only; kpuri's dedicated tests cover null vs "".
                fields = {
                    'protocol': ('scheme', upstream['protocol'][:-1]),
                    'username': ('encodedUsername', upstream['username']),
                    'password': ('encodedPassword', upstream['password']),
                    'hostname': ('encodedHost', upstream['hostname'].removeprefix('[').removesuffix(']')),
                    'port': ('port', upstream['port']),
                    'pathname': ('encodedPath', upstream['pathname']),
                    'search': ('encodedQuery', upstream['search'][1:]),
                    'hash': ('encodedFragment', upstream['hash'][1:]),
                }
                for field, (property_name, value) in fields.items():
                    if upstream[field]:
                        lines += [f'        assertEquals({literal(value)}, url.{property_name})']
        lines += ['    }']
    generated = '\n'.join(lines + ['}', ''])
    if args.check:
        if not OUT.exists() or OUT.read_text() != generated:
            parser.exit(1, 'WptUrlTest.kt is stale; rerun this script without --check\n')
    else:
        OUT.write_text(generated)

if __name__ == '__main__':
    main()
